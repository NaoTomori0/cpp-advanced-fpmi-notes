#include <iostream>

// 2.2 Kinds of memory (Типы памяти)

// Изначально операционная система выделяет некоторую
// область в памяти для нашей программы. Она обычно небольшая,
// примерно где-то 4 МБ.
//
// |=====================================================|
// |        ################ <--- наша память            | <--- RAM
// |=====================================================|
//
// Упрощенно говоря (абстрактно, для наших задач такого понимания пока что хватит):
// у нас эта память делится еще на 3 части.
//
// |=====================================================|
// |      DATA       |      TEXT     |     STACK         | <--- наша память
// |=====================================================|
//
// DATA (Static memory / статическая память)
// В ней хранятся, в частности, глобальные переменные,
// а также другая информация, которая существует в течение
// всего времени выполнения нашей программы.

// TEXT
// Это бинарный код нашей программы на языке машинных инструкций.
// Он загружен в оперативку наряду с нашими данными.

// STACK (Automatic memory / автоматическая память)
// Та область памяти, где хранятся локальные переменные.
//
// При вызове функции на стеке создается ее кадр с переменными,
// а при выходе из функции этот кадр мгновенно уничтожается.
// Память выделяется очень быстро (простым сдвигом указателя процессора).
//
// Имеет жесткий лимит размера (обычно до 8 МБ). Если выделить
// слишком много, программа упадет с ошибкой Stack Overflow.
//
//  Наша память
// |=========================================================================|
// |    TEXT     |     DATA     |      HEAP     |    ...    |     STACK      |
// |   (Код)     |   (Статика)  |    (Куча)     |           |    (Стек)      |
// |=========================================================================|
//                          │                     ▲
//                          ▼                     │
//                   Растет "вниз"          Растет "вверх"
//                   (к старшим             (к младшим
//                    адресам)               адресам)
//
//
//
// Как стек работает при вызове функций (принцип LIFO):
//
// |                     |     |                     |     |                     |
// |                     |     |  [ кадр funcB ]     |     |                     |
// |  [ кадр funcA ]     | --> |  [ кадр funcA ]     | --> |  [ кадр funcA ]     |
// |____[ кадр main ]____|     |____[ кадр main ]____|     |____[ кадр main ]____|
//    Шаг 1: в main()               Шаг 2: funcA()              Шаг 3: funcB()
//    вызвали funcA()               вызвала funcB()             завершилась (умерла)
//
//
//
// ASCII-визуализация памяти стека с адресом возврата (Адреса условные):
//
// Адрес:     Память стека:          Описание:
// 0x100C  |    int y = 10   |  <--- [кадр funcB] Локальная переменная
// 0x1008  | Адрес возврата  |  <--- [Служебные данные] Куда вернуться в funcA после funcB
// 0x1004  |    int x = 5    |  <--- [кадр funcA] Локальная переменная
// 0x1000  |   int main_x = 0|  <--- [кадр main]  Самый первый кадр внизу стека
//         |_________________|
//
//
//
// Указатель стека (регистр процессора) всегда указывает на текущую вершину.
// При вызове funcB() он сдвигается на адрес 0x100C, а при выходе — падает назад на 0x1004.
//
// Зачем нужен адрес возврата
// Когда вызывается funcB(), процессор должен запомнить точку в коде funcA(),
// куда нужно передать управление после завершения funcB().
// Этот адрес (инструкция из сегмента TEXT) автоматически кладется на стек [1].

void funcB()
{
    int y = 10; // Переменная y живет на самом верху стека в кадре funcB
} // <--- Процессор берет адрес возврата со стека и прыгает обратно в funcA

void funcA()
{
    int x = 5; // Переменная x живет в кадре funcA
    funcB();   // Вызываем funcB, ее кадр ложится на стек выше, чем funcA

    x = 42; // <--- Сюда указывает адрес возврата!
}

int stackOverflow(int x)
{
    std::cout << ++x << std::endl;
    return stackOverflow(x);
}
// Почему происходит падение:
// Каждый рекурсивный вызов бесконечно складывает кадры функций друг на друга.
// В каждом кадре выделяется память под аргумент x и адрес возврата.
//
// Указатель стека сдвигается все дальше, пока не выйдет за лимит в 4-8 МБ.
// Программа пытается залезть в чужую память ОС, срабатывает защита железа,
// и операционная система мгновенно убивает процесс (Segmentation fault).

// HEAP (Dynamic memory / динамическая память / Куча)

// |===========================================================|
// |  ################ <--- наша память       |  HEAP  |       | <--- RAM
// |===========================================================|

void dynamicMemory()
{
    int *p = new int;
    // new просит у операционной системы sizeof(T) байт в куче (HEAP).
    // Когда операционная система их выдаст, она вернет указатель на
    // первый байт той области, которую нам выделили.

    delete p;
    // Освобождаем память обратно ОС. Иначе будет утечка памяти!

    int *pa = new int[1'000]; // Выделяем память под массив из 1000 элементов int
    // В C++ начиная с C++14 можно использовать одинарную кавычку ' как разделитель цифр

    delete[] pa; // Важно: для массивов всегда используем delete[]!
    // Если написать просто delete pa, то очистится только первый элемент,
    // либо программа упадет с ошибкой (Undefined Behavior).
}

int main()
{
    stackOverflow(0); // Segmentation fault
    // В какой-то момент программа начнет обращаться к недоступной ей памяти,
    // так как лимит стека (например, 8 МБ) полностью исчерпается.
    return 0;
}